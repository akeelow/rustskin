def arc_poly(x0, x1, y_edge, bulge, y_far, n=12):
    """Контур «язык»: дуга по x0…x1 на y_edge, середина выгнута на bulge (px, + к запястью), низ — y_far."""
    pts = []
    for k in range(n + 1):
        t = -1 + 2 * k / n
        pts.append((x0 + (x1 - x0) * (t + 1) / 2, y_edge - bulge * (1 - t * t)))
    pts += [(x1, y_far), (x0, y_far)]
    return pts


def pad_polys():
    """Подушечки: ладонная часть (на острове 2) и напёрсток на тыле кончика (остров 1)."""
