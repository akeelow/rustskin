def poly_area(p):
    return 0.5 * sum(p[i][0] * p[(i + 1) % len(p)][1] - p[(i + 1) % len(p)][0] * p[i][1] for i in range(len(p)))


def resample(poly, step_px, closed=True):
    """Точки по контуру с шагом step_px (в px атласа 1024), с касательной."""
    pts = list(poly) + ([poly[0]] if closed else [])
    out = []
    carry = 0.0
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        L = math.hypot(bx - ax, by - ay)
        if L < 1e-9:
            continue
        tx, ty = (bx - ax) / L, (by - ay) / L
        s = carry
        while s < L:
            out.append((ax + tx * s, ay + ty * s, tx, ty))
            s += step_px
        carry = s - L
    return out
